# Generate formatted JS
def format_js(obj_list):
    res = ""
    for obj in obj_list:
        res += "\t{\n"
        for k, v in obj.items():
            val_str = json.dumps(v, ensure_ascii=False, indent=1)
            lines = val_str.split('\n')
            indented_lines = [lines[0]]
            for l in lines[1:]:
                stripped = l.lstrip(' ')
                indent_len = len(l) - len(stripped)
                # Each space is 1 level of indent
                indented_lines.append("\t\t" + ("\t" * indent_len) + stripped)
            val_str = "\n".join(indented_lines)
            
            res += f'\t\t"{k}": {val_str},\n'
        # Remove last comma and close
        res = res.rstrip(',\n') + "\n\t},\n"
    return res

formatted_content = format_js(output)
